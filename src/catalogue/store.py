"""PostgreSQL store for extracted PDF catalogues.

The Catalogues page used to re-read a PDF on every open (5-20 s each). Each catalogue is
now extracted once, saved here, and read back in milliseconds. A new PDF is loaded only
when someone runs the load for it (``python -m src.cli catalogue-load``).

Tables, as laid out in the owner's diagram (2026-09-27):

* ``catalogues`` — one row per PDF: ``catalogue_id``, ``catalogue_no`` (the cover's
  publication number, unique, NULL where the book prints none), ``catalogue_year``,
  ``source_file`` (its path under ``pdf_catalogues``), with the file's SHA-256 so a
  changed file is noticed. Excluded catalogues are recorded with the reason, no parts.
* ``models`` — ``model_code`` (the variant, e.g. B65L) and ``model_name`` (its model
  folder, e.g. AEROX).
* ``catalogue_parts`` — one row per part row **per model it is fitted to**:
  ``section``, ``part_no``, ``description``, ``model_code`` (FK to ``models``),
  ``quantity`` for that model, ``remarks``. A row priced for no model is stored once
  with ``model_code`` NULL and a ``row_kind`` naming why (``kit_note``, ``kit_header``).
* ``catalogue_colours`` — the applicable-colour table as extracted.
* ``part_compatible_models`` (view) — per ``part_no``: its description and the
  ``compatible_models`` array ("AEROX - B65L"), plus a separator-free ``material_key``
  so an SAP material id finds it.

Everything the reader produced is kept, so a stored catalogue reads back as the same
``ExtractionResult`` a live extraction returns and the page cannot tell the two apart.
Every write is reconciled against the extraction it came from inside the transaction; a
mismatch rolls back.
"""

